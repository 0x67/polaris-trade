#[test]
fn mixed_set_deletes_nothing() {
    let root = tmp_repo_root("mixed-set-deletes-nothing");
    let schema = toy_schema();
    let owned = owned_module_dir(&schema, &venue_crate_dir(&schema)).unwrap();
    let files = materialize(&root, &schema);

    let marked_rel = owned.join("view").join("marked.rs");
    let hand_rel = owned.join("view").join("hand.rs");
    std::fs::write(
        root.join(&marked_rel),
        format!("{MARKER}fn marked() {{}}\n"),
    )
    .unwrap();
    std::fs::write(root.join(&hand_rel), "fn hand_written() {}\n").unwrap();

    let orphans = find_orphans(&root, &owned, &files);
    assert_eq!(orphans, vec![hand_rel.clone(), marked_rel.clone()]);

    // classify-then-delete: one foreign file in the set means nothing gets deleted,
    // even the file that IS marked.
    let err = prune_orphans(&root, &orphans).unwrap_err();
    assert!(matches!(err, PruneError::Foreign { .. }));
    assert!(root.join(&marked_rel).exists());
    assert!(root.join(&hand_rel).exists());

    let _ = std::fs::remove_dir_all(&root);
}

#[cfg(unix)]
#[test]
fn unreadable_counts_as_foreign() {
    use std::os::unix::fs::PermissionsExt;

    let root = tmp_repo_root("unreadable-counts-as-foreign");
    let schema = toy_schema();
    let owned = owned_module_dir(&schema, &venue_crate_dir(&schema)).unwrap();
    let files = materialize(&root, &schema);

    let orphan_rel = owned.join("view").join("secret.rs");
    let orphan_full = root.join(&orphan_rel);
    std::fs::write(&orphan_full, format!("{MARKER}fn secret() {{}}\n")).unwrap();
    std::fs::set_permissions(&orphan_full, std::fs::Permissions::from_mode(0o000)).unwrap();

    // root (or a filesystem ignoring POSIX perms) can still read a 0o000 file; skip
    // rather than assert a platform-dependent outcome.
    if std::fs::File::open(&orphan_full).is_ok() {
        eprintln!("skip unreadable_counts_as_foreign: file still readable (running as root?)");
        std::fs::set_permissions(&orphan_full, std::fs::Permissions::from_mode(0o644)).unwrap();
        let _ = std::fs::remove_dir_all(&root);
        return;
    }

    let orphans = find_orphans(&root, &owned, &files);
    assert_eq!(orphans, vec![orphan_rel.clone()]);

    let err = prune_orphans(&root, &orphans).unwrap_err();
    assert!(matches!(err, PruneError::Foreign { path } if path == orphan_rel));

    // restore perms so tempdir cleanup below can actually remove the file.
    std::fs::set_permissions(&orphan_full, std::fs::Permissions::from_mode(0o644)).unwrap();
    let _ = std::fs::remove_dir_all(&root);
}

