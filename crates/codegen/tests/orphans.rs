//! Generated-tree ownership: write mode prunes marked stray files under the owned
//! module dir, refuses to touch anything it cannot prove is generated, and check
//! mode reports any stray path (marker-blind) as drift.

use std::path::{Path, PathBuf};

use proto_codegen::{
    cli::{PruneError, find_orphans, prune_orphans, venue_crate_dir, write_outputs},
    emit::{GeneratedFile, generate, owned_module_dir},
    schema::{Endianness, Field, Kind, SchemaFile, TypeClass},
};

fn toy_schema() -> SchemaFile {
    SchemaFile {
        venue: "toyv".to_string(),
        protocol: "orph".to_string(),
        doc_version: "1.0.0".to_string(),
        major: None,
        endianness: Endianness::Be,
        kinds: vec![Kind {
            name: "Thing".to_string(),
            byte: b'A',
            byte_len: Some(2),
            variable: false,
            since: None,
            defect: None,
            doc: None,
            fields: vec![Field {
                name: "v".to_string(),
                width: 1,
                class: TypeClass::Code,
                doc: None,
            }],
            direction: None,
            appendage: Vec::new(),
            appendage_optional: false,
        }],
        appendage_tags: Vec::new(),
    }
}

/// fresh, uniquely named tempdir standing in for a repo root; caller cleans up.
fn tmp_repo_root(label: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "proto-codegen-orphans-{label}-{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("create tempdir repo root");
    dir
}

/// generate the toy schema's expected files and write them onto `root`, mirroring
/// what `main.rs` write mode does before the prune step runs.
fn materialize(root: &Path, schema: &SchemaFile) -> Vec<GeneratedFile> {
    std::fs::create_dir_all(root.join(venue_crate_dir(schema))).expect("create venue crate shell");
    let files = generate(
        schema,
        &venue_crate_dir(schema),
        "schemas/toyv/orph/v1.yaml",
        b"toy bytes",
    )
    .expect("generate");
    write_outputs(root, &files).expect("write generated files");
    files
}

const MARKER: &str = "//! GENERATED by proto-codegen v0.0.0-test\n";

#[test]
fn marked_orphan_pruned() {
    let root = tmp_repo_root("marked-orphan-pruned");
    let schema = toy_schema();
    let owned = owned_module_dir(&schema, &venue_crate_dir(&schema)).unwrap();
    let files = materialize(&root, &schema);

    let orphan_rel = owned.join("view").join("zzz.rs");
    std::fs::write(root.join(&orphan_rel), format!("{MARKER}fn zzz() {{}}\n")).unwrap();

    let orphans = find_orphans(&root, &owned, &files);
    assert_eq!(orphans, vec![orphan_rel.clone()]);

    let deleted = prune_orphans(&root, &orphans).expect("marked orphan prunes clean");
    assert_eq!(deleted, vec![orphan_rel.clone()]);
    assert!(!root.join(&orphan_rel).exists());

    let _ = std::fs::remove_dir_all(&root);
}

